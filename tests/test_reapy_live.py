# Test 2: Set snippet actually changes param values in REAPER
# ---------------------------------------------------------------------------

class TestSetSnippet:
    def _get_params(self, param_names):
        """Read current normalized values for a list of display names."""
        import reapy
        values = {}
        with reapy.inside_reaper():
            fx = reapy.Project().tracks[0].fxs[0]
            for name in param_names:
                try:
                    values[name] = fx.params[name].normalized
                except Exception:
                    pass
        return values

    def _extract_set_params(self, action_snippet):
        """Extract {display_name: value} from action_snippet."""
        params = {}
        for match in re.finditer(r'fx\.params\["([^"]+)"\]\.value\s*=\s*([0-9.]+)',
                                  action_snippet):
            params[match.group(1)] = float(match.group(2))
        return params

    def test_params_change_after_set(self, reapy_fx, path_iter):
        import reapy
        snippet = path_iter["action_snippet"]
        expected = self._extract_set_params(snippet)
        assert expected, "No fx.params assignments found in action_snippet"

        # Read before
        before = self._get_params(list(expected.keys()))

        # Execute set snippet
        with reapy.inside_reaper():
            ns = {"reapy": reapy}
            exec(compile(snippet, "<set>", "exec"), ns)

        # Read after
        after = self._get_params(list(expected.keys()))

        # At least some params should have changed
        changed = [k for k in expected if abs(after.get(k, -1) - expected[k]) < 0.01]
        assert len(changed) > 0, (
            f"No params reached expected values. Expected: {expected}, Got: {after}"
        )

    def test_normalized_values_match_params_applied(self, reapy_fx, path_iter):
        """Values in snippet should match params_applied within tolerance."""
        import reapy
        snippet = path_iter["action_snippet"]
        expected = self._extract_set_params(snippet)

        with reapy.inside_reaper():
            ns = {"reapy": reapy}
            exec(compile(snippet, "<set>", "exec"), ns)

        after = self._get_params(list(expected.keys()))
        for name, exp_val in expected.items():
            got = after.get(name)
            if got is not None:
                assert abs(got - exp_val) < 0.005, (
                    f"Param '{name}': expected {exp_val:.4f}, got {got:.4f}"
                )


