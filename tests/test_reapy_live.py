class TestSearchSnippet:
    def test_executes_without_error(self, reapy_fx, path_iter):
        import reapy
        snippet = path_iter["search_snippet"]
        # Execute in a controlled namespace with reapy context
        buf = io.StringIO()
        with reapy.inside_reaper():
            ns = {"reapy": reapy}
            exec(compile(snippet, "<search>", "exec"), ns)

    def test_output_format(self, reapy_fx, path_iter):
        """Each output line should be 'Param Name: 0.XXXX'."""
        import reapy
        snippet = path_iter["search_snippet"]
        lines = []
        # Capture print output by patching builtins.print in the exec namespace
        captured = []

        def fake_print(*args, **kwargs):
            captured.append(" ".join(str(a) for a in args))

        with reapy.inside_reaper():
            ns = {"reapy": reapy, "print": fake_print}
            exec(compile(snippet, "<search>", "exec"), ns)

        assert captured, "Search produced no output"
        for line in captured:
            assert ": " in line, f"Line missing ': ': {line!r}"
            val_str = line.rsplit(": ", 1)[1]
            val = float(val_str)
            assert 0.0 <= val <= 1.0, f"Value {val} out of [0,1] in line: {line!r}"

    def test_keyword_present_in_all_names(self, reapy_fx, path_iter):
        """All returned param names should contain the search keyword."""
        import reapy
        keyword = path_iter["search_keyword"]
        captured = []

        def fake_print(*args, **kwargs):
            captured.append(" ".join(str(a) for a in args))

        with reapy.inside_reaper():
            ns = {"reapy": reapy, "print": fake_print}
            exec(compile(path_iter["search_snippet"], "<search>", "exec"), ns)

        for line in captured:
            name = line.rsplit(": ", 1)[0]
            assert keyword in name.lower(), (
                f"keyword '{keyword}' not found in param name '{name}'"
            )


