class TestFullIterationCycle:
    def test_cycle_completes(self, reapy_fx, path_iter):
        """Run search → set → render in sequence without errors."""
        import reapy

        # Search
        with reapy.inside_reaper():
            ns = {"reapy": reapy}
            exec(compile(path_iter["search_snippet"], "<search>", "exec"), ns)

        # Set
        with reapy.inside_reaper():
            ns = {"reapy": reapy}
            exec(compile(path_iter["action_snippet"], "<set>", "exec"), ns)

        # Render
        result = subprocess.run(
            [sys.executable, "scripts/reaper_render_probe.py"],
            capture_output=True, text=True,
            cwd=str(Path(__file__).parent.parent),
        )
        assert result.returncode == 0
        assert Path("/tmp/probe.wav").is_file()


