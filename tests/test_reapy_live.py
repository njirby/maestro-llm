# Test 3: reaper_render_probe.py produces a valid WAV at /tmp/probe.wav
# ---------------------------------------------------------------------------

class TestRenderProbe:
    def test_file_created(self, reapy_fx):
        out = Path("/tmp/probe.wav")
        if out.exists():
            out.unlink()

        result = subprocess.run(
            [sys.executable, "scripts/reaper_render_probe.py"],
            capture_output=True, text=True,
            cwd=str(Path(__file__).parent.parent),
        )
        assert result.returncode == 0, f"render_probe failed:\n{result.stderr}"
        assert out.is_file(), "/tmp/probe.wav not created"
        assert out.stat().st_size > 44, "WAV file too small (just a header?)"

    def test_valid_wav(self, reapy_fx):
        subprocess.run(
            [sys.executable, "scripts/reaper_render_probe.py"],
            capture_output=True,
            cwd=str(Path(__file__).parent.parent),
        )
        with wave.open("/tmp/probe.wav") as w:
            assert w.getnframes() > 0, "WAV has zero frames"
            assert w.getnchannels() in (1, 2)
            assert w.getframerate() > 0

    def test_stdout_message(self, reapy_fx):
        result = subprocess.run(
            [sys.executable, "scripts/reaper_render_probe.py"],
            capture_output=True, text=True,
            cwd=str(Path(__file__).parent.parent),
        )
        assert "probe.wav" in result.stdout


