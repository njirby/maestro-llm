# Test 5: Search result matches live REAPER state (init preset)
# ---------------------------------------------------------------------------

class TestSearchResultMatchesLive:
    def test_param_names_present_in_live(self, reapy_fx, path_iter):
        """Param names from synthetic search_result should exist in live fx.params."""
        import reapy

        # Get live param names
        with reapy.inside_reaper():
            fx = reapy.Project().tracks[0].fxs[0]
            live_names = {p.name for p in fx.params}

        # Check synthetic result names against live
        result = path_iter["search_result"]
        if not result:
            pytest.skip("empty search result for this iteration")

        missing = []
        for line in result.splitlines():
            name = line.rsplit(": ", 1)[0]
            if name not in live_names:
                missing.append(name)

        # Allow up to 10% mismatch (heuristic display name vs actual REAPER name)
        total = len(result.splitlines())
        assert len(missing) / total < 0.10, (
            f"{len(missing)}/{total} synthetic names not found in live REAPER: {missing[:5]}"
        )
